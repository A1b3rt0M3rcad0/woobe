from typing import Protocol

from modules.artifacts.application.contracts.indexes import IndexPhase, ListIndexNodes, ReadIndex, ReadIndexNode
from modules.artifacts.application.contracts.jobs import JobLease


class DocumentIndexStore(Protocol):
    async def prepare(self, request: IndexPhase): ...
    async def metadata(self, request: IndexPhase): ...
    async def seal(self, request: IndexPhase): ...
    async def commit_ready(self, lease: JobLease, publication: dict, result: dict): ...
    async def read(self, request: ReadIndex): ...
    async def node(self, request: ReadIndexNode): ...
    async def nodes(self, request: ListIndexNodes, after: int | None): ...
