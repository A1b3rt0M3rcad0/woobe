from typing import Protocol

from modules.artifacts.application.contracts.uploads import (
    BeginUpload, CommitUpload, RecordPart, UploadRequest, UploadSnapshot,
)


class UploadStore(Protocol):
    async def begin(self, request: BeginUpload, subject: str) -> UploadSnapshot: ...
    async def load(self, request: UploadRequest, subject: str) -> UploadSnapshot: ...
    async def record_part(self, request: RecordPart, subject: str) -> UploadSnapshot: ...
    async def verify(self, request: UploadRequest, subject: str) -> UploadSnapshot: ...
    async def commit(self, request: CommitUpload, subject: str) -> UploadSnapshot: ...
    async def abort(self, request: UploadRequest, subject: str) -> UploadSnapshot: ...
