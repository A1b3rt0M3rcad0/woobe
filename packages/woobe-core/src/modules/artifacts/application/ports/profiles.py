from typing import Protocol

from modules.artifacts.application.contracts.processing import ProfileCreate
from modules.artifacts.domain.models import Scope


class ProfileStore(Protocol):
    async def create(self, scope: Scope, definition: ProfileCreate): ...
    async def get(self, scope: Scope, profile_id: str, revision: int): ...
    async def page(self, scope: Scope, *, after: str | None, limit: int): ...
    async def bind(self, scope: Scope, workspace_id: str, definition): ...
