from typing import Protocol

from modules.artifacts.application.contracts.jobs import JobLease
from modules.artifacts.application.contracts.representations import BundlePhase, RecordProcessingObject, ReserveProcessingObject
from modules.artifacts.domain.models import Scope


class RepresentationStore(Protocol):
    async def lock_scope(self, scope: Scope, workspace_id: str): ...
    async def reserve(self, request: ReserveProcessingObject): ...
    async def record(self, request: RecordProcessingObject): ...
    async def prepare(self, request: BundlePhase, source): ...
    async def metadata(self, request: BundlePhase): ...
    async def seal(self, request: BundlePhase): ...
    async def commit_ready(self, lease: JobLease, publication: dict, result: dict): ...
    async def read(self, request): ...
    async def entries(self, request, after): ...
    async def source(self, request): ...
