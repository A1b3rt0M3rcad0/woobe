from typing import Protocol

from modules.artifacts.application.contracts.jobs import (
    ClaimProcessingJob, JobLease, ProcessingJobView, ReadProcessingJob, RequestProcessing, WorkerPhase,
)
from modules.artifacts.application.contracts.processing import ProcessingRecipe


class ProcessingJobStore(Protocol):
    async def request(self, request: RequestProcessing, source, recipe: ProcessingRecipe,
                      profile_id: str | None, profile_revision: int | None) -> ProcessingJobView: ...
    async def lookup(self, request: RequestProcessing, subject: str) -> ProcessingJobView | None: ...
    async def read(self, request: ReadProcessingJob, subject: str) -> ProcessingJobView: ...
    async def cancel(self, request: ReadProcessingJob, subject: str) -> ProcessingJobView: ...
    async def deliver(self, limit: int) -> int: ...
    async def claim(self, request: ClaimProcessingJob) -> JobLease | None: ...
    async def guard(self, lease: JobLease): ...
    async def heartbeat(self, phase: WorkerPhase) -> bool: ...
    async def checkpoint(self, phase: WorkerPhase): ...
    async def terminal_ack(self, phase: WorkerPhase) -> bool | None: ...
    async def finish(self, phase: WorkerPhase): ...
