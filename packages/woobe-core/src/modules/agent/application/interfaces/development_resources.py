from typing import Protocol


class DevelopmentResources(Protocol):
    async def prepare_existing(self, data: dict, agent_id: str) -> dict: ...
    async def reuse(self, data: dict, principal) -> dict: ...
    async def reuse_frozen(self, data: dict, principal) -> dict: ...
    async def find_artifact(self, kind: str, data: dict) -> dict | None: ...
